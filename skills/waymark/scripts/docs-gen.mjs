#!/usr/bin/env node
// Waymark · the generated parts of README.md besides the agent matrix (matrix.mjs): the index of the decision records
// (docs/adr) and the table of measured sizes (size.mjs --readme). Both sit between markers; tests/docs.test.mjs fails when the
// README differs from what this prints, so a new ADR cannot be left out and a figure cannot drift.
//   node docs-gen.mjs           print the ADR index
//   node docs-gen.mjs --write   put the ADR index between the markers of README.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
export const ADR_BEGIN = '<!-- adr-index:begin (generated by skills/waymark/scripts/docs-gen.mjs --write; do not edit) -->';
export const ADR_END = '<!-- adr-index:end -->';

// → "- [0001 · Title](docs/adr/0001-….md)" per record, in order. The title is the first heading without its number.
export function adrIndex(root = ROOT) {
  const dir = path.join(root, 'docs', 'adr');
  return fs.readdirSync(dir).filter((f) => /^\d{4}-.+\.md$/.test(f)).sort().map((f) => {
    const heading = fs.readFileSync(path.join(dir, f), 'utf8').split('\n').find((l) => /^#\s/.test(l)) || `# ${f}`;
    const title = heading.replace(/^#\s*/, '').replace(/^(ADR\s*)?\d{4}\s*[·:.-]\s*/i, '').trim();
    return `- [${f.slice(0, 4)} · ${title}](docs/adr/${f})`;
  }).join('\n');
}

// The text between two markers of a document, or null.
export function between(text, begin, end) {
  const i = text.indexOf(begin), j = text.indexOf(end);
  return i >= 0 && j > i ? text.slice(i + begin.length + 1, j - 1) : null;
}

if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const md = adrIndex();
  if (process.argv.includes('--write')) {
    const file = path.join(ROOT, 'README.md'), text = fs.readFileSync(file, 'utf8');
    if (!text.includes(ADR_BEGIN)) { console.log('README.md: no adr-index marker'); process.exit(1); }
    const i = text.indexOf(ADR_BEGIN), j = text.indexOf(ADR_END) + ADR_END.length;
    fs.writeFileSync(file, text.slice(0, i) + `${ADR_BEGIN}\n${md}\n${ADR_END}` + text.slice(j));
    console.log('README.md: ADR index written');
  } else console.log(md);
}
