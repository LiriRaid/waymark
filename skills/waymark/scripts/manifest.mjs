#!/usr/bin/env node
// Waymark · the manifest of a release (docs/adr/0027): the sha256 of every file under skills/, in skills/waymark/MANIFEST.json,
// so an installed copy can be compared with what was released, offline. The manifest never lists itself. Text files are
// hashed with CRLF read as LF, so a copy checked out on Windows matches one from Linux.
//   node manifest.mjs            check the manifest of this install against its files (exit 1 when it differs)
//   node manifest.mjs --sign <ssh private key>   sign it: MANIFEST.json.sig, checked by verify --install (the release checklist)
//   node manifest.mjs --write    rebuild it (the release checklist runs this; tests/supply-chain-verify.test.mjs checks it is current)
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { sha } from './lib/hash.mjs';
import { identityOf } from './sign.mjs';

export const SKILLS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const MANIFEST_FILE = path.join(SKILLS, 'waymark', 'MANIFEST.json');
export const SCHEMA = 'waymark.manifest/v1';
export const SIGNATURE_FILE = path.join(SKILLS, 'waymark', 'MANIFEST.json.sig');
// Files the manifest never lists: itself, its signature, and the two that `sync` rewrites for each machine. The generated
// ones are checked by what generates them (checkGenerated), not by a hash.
export const GENERATED = ['waymark/skill-map.json', 'waymark/skill-registry.md'];
const SKIP = new Set(['waymark/MANIFEST.json', 'waymark/MANIFEST.json.sig', ...GENERATED]);
const SKIP_DIR = /(^|\/)(node_modules|\.git|\.waymark|\.engram)(\/|$)/;

// What a Markdown file is hashed as: CRLF read as LF, and the body of its `## Learned rules` / `## Learned notes` section left out. That
// section is where the learning step writes the lessons of the user's own tasks, so an install that learned something is still
// the release (every other line of the file is verified); the heading stays, so removing the section is still a change.
const LEARNED = /^(## Learned (?:rules|notes)[^\n]*)\n[\s\S]*?(?=^## |(?![\s\S]))/gm;
export const hashFile = (file) => {
  const buf = fs.readFileSync(file);
  if (buf.includes(0)) return sha(buf);
  const text = buf.toString('utf8').replace(/\r\n/g, '\n');
  return sha(/\.md$/i.test(file) ? text.replace(LEARNED, '$1\n') : text);
};

// → sorted relative paths (forward slashes) of every file under `dir`.
export function listFiles(dir = SKILLS) {
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const abs = path.join(d, e.name), rel = path.relative(dir, abs).split(path.sep).join('/');
      if (SKIP_DIR.test(rel)) continue;
      if (e.isDirectory()) walk(abs);
      else if (e.isFile() && !SKIP.has(rel)) out.push(rel);
    }
  };
  walk(dir);
  return out.sort();
}

export function buildManifest(dir = SKILLS) {
  const version = (() => { try { return fs.readFileSync(path.join(dir, 'waymark', 'VERSION'), 'utf8').trim(); } catch { return null; } })();
  const files = {};
  for (const rel of listFiles(dir)) files[rel] = hashFile(path.join(dir, rel));
  return { schema: SCHEMA, version, algorithm: 'sha256', files };
}

// The files `sync` writes locally, each against its generator: skill-map.json parses and holds the skills map,
// skill-registry.md carries the header sync writes. → { ok, problems[] }.
export function checkGenerated(dir = SKILLS) {
  const problems = [];
  try {
    const m = JSON.parse(fs.readFileSync(path.join(dir, 'waymark', 'skill-map.json'), 'utf8'));
    if (!m || typeof m.skills !== 'object' || Array.isArray(m.skills)) problems.push('waymark/skill-map.json: no "skills" map');
  } catch { problems.push('waymark/skill-map.json: missing or not JSON'); }
  try {
    if (!/^> Generated by `scripts\/sync\.mjs`/m.test(fs.readFileSync(path.join(dir, 'waymark', 'skill-registry.md'), 'utf8').slice(0, 600))) problems.push('waymark/skill-registry.md: not the registry sync.mjs writes');
  } catch { problems.push('waymark/skill-registry.md: missing'); }
  return { ok: !problems.length, problems };
}

// Compares `dir` with a manifest (default: the one in this install). → { ok, version, checked, missing[], changed[], extra[] }.
export function checkManifest(dir = SKILLS, manifest = null) {
  const m = manifest || JSON.parse(fs.readFileSync(path.join(dir, 'waymark', 'MANIFEST.json'), 'utf8'));
  const missing = [], changed = [];
  for (const [rel, hash] of Object.entries(m.files || {})) {
    const abs = path.join(dir, rel);
    if (!fs.existsSync(abs)) missing.push(rel);
    else if (hashFile(abs) !== hash) changed.push(rel);
  }
  const extra = listFiles(dir).filter((rel) => !(rel in (m.files || {})));
  return { ok: !missing.length && !changed.length && !extra.length, version: m.version || null, checked: Object.keys(m.files || {}).length, missing, changed, extra };
}

// skills.lock (docs/adr/0036): each third-party skill Waymark vendors (`sync --vendor`), pinned to what it was vendored from. The manifest
// already hashes every file of the release; the lock adds where a vendored skill came from and the hash of its folder, so `verify --install`
// says which skill moved and what it was pinned to. { schema, skills: { <name>: { source, ref, upstreamHash, vendoredAt, license, sha256 } } }
export const LOCK_SCHEMA = 'waymark.skills-lock/v1';
const LOCK_ABOUT = 'Third-party skills vendored into this release: where each came from (source, and ref = the tag or commit, or upstreamHash = the upstream folder hash when the source gives no ref) and the sha256 of its folder as vendored, written by `sync --vendor <name>` and checked by `verify --install`.';

export const readSkillsLock = (dir = SKILLS) => { try { return JSON.parse(fs.readFileSync(path.join(dir, 'waymark', 'skills.lock'), 'utf8')); } catch { return null; } };

// The sha256 of one skill's folder: its files, sorted, each by name and hash (hashFile: CRLF as LF, learned sections left out).
export const skillSha = (name, dir = SKILLS) => sha(listFiles(dir).filter((rel) => rel.startsWith(`${name}/`)).map((rel) => `${rel}:${hashFile(path.join(dir, rel))}`).join('\n'));

// Pins `name` in the lock (created when missing). `entry`: { source, ref, upstreamHash, vendoredAt, license }. → the entry written.
export function lockSkill(name, entry, dir = SKILLS) {
  const file = path.join(dir, 'waymark', 'skills.lock');
  const lock = readSkillsLock(dir) || { schema: LOCK_SCHEMA, about: LOCK_ABOUT, skills: {} };
  lock.skills[name] = { source: entry.source || null, ref: entry.ref || null, upstreamHash: entry.upstreamHash || null, vendoredAt: entry.vendoredAt || null, license: entry.license || null, sha256: skillSha(name, dir) };
  lock.skills = Object.fromEntries(Object.entries(lock.skills).sort(([a], [b]) => a.localeCompare(b)));
  fs.writeFileSync(file, JSON.stringify(lock, null, 1) + '\n');
  return lock.skills[name];
}

// The lock against the files: { ok, present, checked, changed[], missing[], unpinned[], problems[] }. changed: the folder is not what was
// pinned; missing: pinned and gone; unpinned: an entry with neither a ref nor an upstream hash (a warning, it names no upstream to return to).
export function checkSkillsLock(dir = SKILLS) {
  const lock = readSkillsLock(dir);
  if (!lock) return { ok: false, present: false, checked: 0, changed: [], missing: [], unpinned: [], problems: ['no skills.lock in this install'] };
  const changed = [], missing = [], unpinned = [], problems = [];
  if (lock.schema !== LOCK_SCHEMA) problems.push(`skills.lock: unknown schema ${lock.schema || '(none)'}`);
  for (const [name, e] of Object.entries(lock.skills || {})) {
    if (!fs.existsSync(path.join(dir, name, 'SKILL.md'))) { missing.push(name); continue; }
    if (!e.sha256 || skillSha(name, dir) !== e.sha256) changed.push(name);
    if (!e.source) problems.push(`${name}: no source`);
    if (!e.ref && !e.upstreamHash) unpinned.push(name);
  }
  return { ok: !changed.length && !missing.length && !problems.length, present: true, checked: Object.keys(lock.skills || {}).length, changed, missing, unpinned, problems };
}

// The signature the release carries: ssh-keygen -Y over the manifest, namespace "waymark", in MANIFEST.json.sig. It signs
// the manifest read with CRLF as LF, so a checkout on any system verifies the same bytes. The public keys it is checked
// against are the ones in waymark/ALLOWED_SIGNERS, so a copy needs no git history to verify it.
const NAMESPACE = 'waymark';
const canonical = (file) => Buffer.from(fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'));
const keygen = (args, input) => spawnSync('ssh-keygen', args, { input, encoding: 'utf8', timeout: 10000 });

// Writes `<manifest>.sig`. → { ok, file, error? }
export function signManifest(keyFile, manifestFile = MANIFEST_FILE) {
  const r = spawnSync('ssh-keygen', ['-Y', 'sign', '-f', keyFile, '-n', NAMESPACE], { input: canonical(manifestFile), encoding: 'utf8', timeout: 60000 });
  if (r.error || r.status !== 0 || !String(r.stdout).includes('BEGIN SSH SIGNATURE')) return { ok: false, error: (r.stderr || r.error?.message || 'ssh-keygen failed').trim() };
  fs.writeFileSync(`${manifestFile}.sig`, r.stdout);
  return { ok: true, file: `${manifestFile}.sig` };
}

// The state of a manifest's signature against the allowed signers (ssh lines of git's allowed-signers format):
// { state: 'signed' | 'untrusted' | 'bad' | 'unsigned' | 'unchecked', by? }. untrusted: a valid signature by a key that is
// not in the file; bad: the manifest or the signature was edited after signing.
export function manifestSignature(manifestFile = MANIFEST_FILE, allowedFile = path.join(path.dirname(manifestFile), 'ALLOWED_SIGNERS')) {
  const sig = `${manifestFile}.sig`;
  if (!fs.existsSync(sig) || !fs.existsSync(manifestFile)) return { state: 'unsigned' };
  const data = canonical(manifestFile);
  let text = '';
  try { text = fs.readFileSync(allowedFile, 'utf8'); } catch {}
  const principals = text.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#') && !/^gpg\s/i.test(l)).map((l) => l.split(/\s+/)[0]);
  for (const who of new Set(principals)) {
    const r = keygen(['-Y', 'verify', '-f', allowedFile, '-I', identityOf(who), '-n', NAMESPACE, '-s', sig], data);
    if (r.error) return { state: 'unchecked' };
    if (r.status === 0) return { state: 'signed', by: who };
  }
  const r = keygen(['-Y', 'check-novalidate', '-n', NAMESPACE, '-s', sig], data);
  if (r.error) return { state: 'unchecked' };
  return { state: r.status === 0 ? 'untrusted' : 'bad' };
}

if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const signAt = process.argv.indexOf('--sign');
  if (signAt > 0) {
    const r = signManifest(process.argv[signAt + 1]);
    console.log(r.ok ? `manifest: signed → ${r.file}` : `manifest: not signed (${r.error})`);
    process.exitCode = r.ok ? 0 : 1;
  } else if (process.argv.includes('--write')) {
    const m = buildManifest();
    fs.writeFileSync(MANIFEST_FILE, JSON.stringify(m, null, 1) + '\n');
    console.log(`manifest: ${Object.keys(m.files).length} files, version ${m.version}`);
  } else {
    const r = checkManifest();
    console.log(r.ok ? `manifest: ${r.checked} files match (version ${r.version})` : `manifest differs: ${r.changed.length} changed, ${r.missing.length} missing, ${r.extra.length} extra\n${[...r.changed.map((f) => `~ ${f}`), ...r.missing.map((f) => `- ${f}`), ...r.extra.map((f) => `+ ${f}`)].slice(0, 20).join('\n')}`);
    process.exitCode = r.ok ? 0 : 1;
  }
}
