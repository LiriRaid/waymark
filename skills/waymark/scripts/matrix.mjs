#!/usr/bin/env node
// Waymark · the per-agent capability matrix (docs/adr/0027), generated from agents/agents.json and the adapters, never written by hand:
// which hook events each agent has, and from them which testigos are ENFORCED (a hook runs and can stop or hand something to the agent)
// and which are ADVISORY (the agent is told in its instructions; nothing stops it). README.md and INSTALL.md carry the result between
// the markers below; tests/docs.test.mjs fails when they differ.
//   node matrix.mjs           print the tables
//   node matrix.mjs --write   put them between the markers of README.md and INSTALL.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..');
export const BEGIN = '<!-- agent-matrix:begin (generated by skills/waymark/scripts/matrix.mjs --write; do not edit) -->';
export const END = '<!-- agent-matrix:end -->';
const EVENTS = ['SessionStart', 'UserPromptSubmit', 'PreToolUse', 'PostToolUse', 'Stop'];

// The events Waymark registers for an agent: the four of the chain, plus those its `extra` lists; a plugin (OpenCode) maps all five.
export function eventsOf(a) {
  if (!a.adapter || !a.hooks) return Object.fromEntries(EVENTS.map((e) => [e, false]));
  if (a.hooks.format === 'plugin') return Object.fromEntries(EVENTS.map((e) => [e, true]));
  const extra = new Set(a.hooks.extra || []), listed = (e) => !a.hooks.events || e in a.hooks.events; // an `events` map names the events the agent has
  return { SessionStart: listed('SessionStart'), UserPromptSubmit: listed('UserPromptSubmit'), PreToolUse: listed('PreToolUse'), PostToolUse: extra.has('PostToolUse') && listed('PostToolUse'), Stop: listed('Stop') };
}

export async function agentMatrix() {
  const agents = JSON.parse(fs.readFileSync(path.join(HERE, 'agents', 'agents.json'), 'utf8')).agents;
  const rows = [];
  for (const a of agents) {
    const ev = eventsOf(a);
    let readsGuarded = false, preContext = false, out = {};
    if (a.adapter) {
      const m = await import(`file://${HERE}/agents/${a.adapter}.mjs`);
      try { readsGuarded = !!m.call?.({ tool_name: 'Read', tool_input: { file_path: 'x' }, cwd: '.' })?.reads; } catch {}
      preContext = !!m.preContext;
      out = m.out || {};
    }
    const has = (x) => (x ? 'enforced' : 'advisory');
    rows.push({
      key: a.key, name: a.name || a.key, adapter: a.adapter || null, events: ev,
      cells: a.adapter ? {
        stop: has(ev.Stop && out.block), gate: has(ev.PreToolUse && out.deny), brake: has(ev.UserPromptSubmit && out.blockPrompt), hand: ev.PreToolUse && preContext ? 'enforced' : ev.PostToolUse ? 'enforced' : 'advisory',
        guard: has(ev.PreToolUse && out.deny), reads: readsGuarded ? 'enforced' : 'advisory',
      } : null,
    });
  }
  return rows;
}

const yes = (b) => (b ? 'yes' : '—');
export function matrixMarkdown(rows) {
  const withHooks = rows.filter((r) => r.adapter), without = rows.filter((r) => !r.adapter);
  const t1 = ['| Agent | SessionStart | UserPromptSubmit | PreToolUse | PostToolUse | Stop |', '|---|---|---|---|---|---|',
    ...withHooks.map((r) => `| ${r.name} | ${EVENTS.map((e) => yes(r.events[e])).join(' | ')} |`)];
  const t2 = ['| Agent | End-of-turn checks | Decision gate and commit trailer | Memory and procedures handed over | Sensitive paths: edits and shell | Sensitive paths: reads | Context brake |', '|---|---|---|---|---|---|---|',
    ...withHooks.map((r) => `| ${r.name} | ${r.cells.stop} | ${r.cells.gate} | ${r.cells.hand} | ${r.cells.guard} | ${r.cells.reads} | ${r.cells.brake} |`)];
  return [
    '**Hook events Waymark registers, per agent** (from `agents/agents.json`):', '', ...t1, '',
    '**What each agent enforces.** *enforced*: a hook runs and can stop the turn or hand the agent the text. *advisory*: the agent is told in its instructions and nothing blocks it.', '', ...t2, '',
    `Agents Waymark knows with no adapter yet (nothing is recorded or checked there): ${without.map((r) => r.name).join(', ') || 'none'}.`,
  ].join('\n');
}

export const block = (md) => `${BEGIN}\n${md}\n${END}`;
// The text between the markers of a file, or null when it has none.
export function between(text) {
  const i = text.indexOf(BEGIN), j = text.indexOf(END);
  return i >= 0 && j > i ? text.slice(i + BEGIN.length + 1, j - 1) : null;
}

if (process.argv[1] && fs.realpathSync(path.resolve(process.argv[1])) === fileURLToPath(import.meta.url)) {
  const md = matrixMarkdown(await agentMatrix());
  if (process.argv.includes('--write')) {
    for (const f of ['README.md', 'INSTALL.md']) {
      const file = path.join(ROOT, f), text = fs.readFileSync(file, 'utf8');
      if (!text.includes(BEGIN)) { console.log(`${f}: no marker, skipped`); continue; }
      fs.writeFileSync(file, text.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), () => block(md)));
      console.log(`${f}: matrix written`);
    }
  } else console.log(md);
}
